import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../../client/',import.meta.url));
const table=JSON.parse(await readFile(new URL('./commontext-export.json',import.meta.url),'utf8'));
const rows=table.rows.map(r=>Object.fromEntries(r.cells.map(c=>[c.field,c.value])));
const values={},constants=[];
for(const row of rows){
 if(!/^[A-Z][A-Z0-9_]*$/.test(row.ID)||!/^\d+$/.test(row.NumID)||values[row.NumID])throw Error('Invalid/duplicate CommonText row');
 values[row.NumID]=row.Context;constants.push(`        public const int ${row.ID} = ${row.NumID};`);
}
await mkdir(root+'/Assets/Scripts/Config',{recursive:true});
await mkdir(root+'/Assets/Resources',{recursive:true});
await writeFile(root+'/Assets/Scripts/Config/CommonTextIds.g.cs','// <auto-generated>From practice/config/propCommonText.xlsx via UnityCLI Excel export.</auto-generated>\nnamespace Config\n{\n    public static class Excel\n    {\n'+constants.join('\n')+'\n    }\n}\n');
await writeFile(root+'/Assets/Resources/PracticeCommonText.json',JSON.stringify(values,null,2));
console.log('Exported '+rows.length+' CommonText entries. Source language only; no translated language table was provided.');
